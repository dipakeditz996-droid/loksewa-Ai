class User(AbstractUser):
    ROLE_CHOICES = (
        ('student', 'Student'),
        ('teacher', 'Teacher'),
        ('admin', 'Admin'),
        ('super-admin', 'Super Admin'),
    )
    role = models.CharField(max_length=20, choices=ROLE_CHOICES, default='student')
    avatar = models.URLField(blank=True, null=True)

    # Account lockout (Admin Settings > Security > Max Login Attempts).
    failed_login_attempts = models.PositiveIntegerField(default=0)
    locked_until = models.DateTimeField(null=True, blank=True)

    # Two-factor auth (Admin Settings > Security > Two-Factor Authentication).
    # totp_secret is written as soon as setup starts, but is_2fa_enabled only
    # flips to True once the user proves they can generate a valid code with
    # it - an unconfirmed secret never gates login.
    totp_secret = models.CharField(max_length=32, blank=True, null=True)
    is_2fa_enabled = models.BooleanField(default=False)

    # Single active login session tracking: stores the current active session key.
    # Every new login rotates this key atomically, immediately invalidating old sessions.
    jwt_session_key = models.CharField(max_length=64, blank=True, null=True, db_index=True)

    def is_subscribed_to(self, category: str, event_key: str = None) -> bool:
        """Checks if this admin recipient is subscribed to a specific category and event."""
        if not self.is_active:
            return False
        if self.event_categories and category not in self.event_categories:
            return False
        if self.subscribed_events and event_key and event_key not in self.subscribed_events:
            return False
        return True

    def __str__(self):
        return f"{self.username} ({self.role})"

    def save(self, *args, **kwargs):
        if self.role in ('admin', 'super-admin'):
            self.is_staff = True
        super().save(*args, **kwargs)


class EmailOTP(models.Model):
    """A one-time verification code for signup verification, password-reset
    confirmation, or admin-assisted recovery verification. Stored hashed,
    never in plaintext.

    'admin_recovery' reuses this same model/verification path rather than a
    separate one: it's generated by an admin (not self-service, and not
    emailed at all - the admin relays it through a secure support channel)
    but otherwise has identical security properties (hashed, short-lived,
    single-use, attempt-capped) to the signup/password-reset codes, via the
    same create/verify functions in core/otp.py.
    """
    PURPOSE_CHOICES = (
        ('signup', 'Signup Verification'),
        ('password_reset', 'Password Reset'),
        ('admin_recovery', 'Admin-Assisted Recovery'),
    )
    email = models.EmailField(db_index=True)
    purpose = models.CharField(max_length=20, choices=PURPOSE_CHOICES)
    code_hash = models.CharField(max_length=64)
    attempts = models.PositiveIntegerField(default=0)
    is_used = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)
    expires_at = models.DateTimeField()
    # Only set for purpose='admin_recovery' - which admin generated this
    # code, for the pending-verification panel and audit trail.
    generated_by = models.ForeignKey(
        'core.User', on_delete=models.SET_NULL, null=True, blank=True, related_name='otps_generated'
    )

    class Meta:
        indexes = [models.Index(fields=['email', 'purpose', 'is_used'])]

    def is_subscribed_to(self, category: str, event_key: str = None) -> bool:
        """Checks if this admin recipient is subscribed to a specific category and event."""
        if not self.is_active:
            return False
        if self.event_categories and category not in self.event_categories:
            return False
        if self.subscribed_events and event_key and event_key not in self.subscribed_events:
            return False
        return True

    def __str__(self):
        return f"OTP for {self.email} ({self.purpose})"


